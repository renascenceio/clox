#!/usr/bin/env node
/**
 * Regenerates src/lib/gateway/catalog.generated.ts from the public
 * Vercel AI Gateway model list (https://ai-gateway.vercel.sh/v1/models).
 *
 *   node scripts/sync-gateway-models.mjs
 *
 * Every model the app offers comes from this file, so rerun it whenever
 * the gateway adds or retires models. Batch variants, deprecated models,
 * and types the app has no surface for (embeddings, reranking, realtime,
 * evaluation) are left out.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/gateway/catalog.generated.ts')
const KEEP_TYPES = new Set(['language', 'image', 'video', 'speech', 'transcription'])

const res = await fetch('https://ai-gateway.vercel.sh/v1/models')
if (!res.ok) throw new Error(`Gateway model list ${res.status}`)
const { data } = await res.json()

function firstSentence(text) {
  if (!text) return ''
  const flat = text.replace(/\s+/g, ' ').trim()
  const cut = flat.match(/^.{20,220}?[.!?](?=\s|$)/)
  const s = cut ? cut[0] : flat.slice(0, 200)
  return s.length < flat.length && !cut ? `${s}…` : s
}

const now = Date.now()
const entries = data
  .filter(m => KEEP_TYPES.has(m.type))
  .filter(m => !/-batch$/.test(m.id))
  .filter(m => !m.deprecated_at || m.deprecated_at > now)
  .map(m => {
    const e = {
      id: m.id,
      name: m.name,
      owner: m.id.split('/')[0],
      type: m.type,
      released: m.released ?? 0,
    }
    const blurb = firstSentence(m.description)
    if (blurb) e.description = blurb
    if (m.context_window) e.context = m.context_window
    if (m.max_tokens) e.maxOutput = m.max_tokens
    if (m.tags?.length) e.tags = m.tags
    if (m.modalities) e.input = m.modalities.input, e.output = m.modalities.output
    if (m.supported_parameters?.length) e.params = m.supported_parameters
    if (m.temperature !== undefined) e.temperature = m.temperature
    if (m.reasoning_options?.length) e.reasoning = m.reasoning_options
    if (m.video_capabilities) e.video = m.video_capabilities
    return e
  })
  .sort((a, b) => a.id.localeCompare(b.id))

const body = `/* eslint-disable */
// GENERATED by scripts/sync-gateway-models.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand — rerun the script to refresh.
import type { GatewayCatalogEntry } from './types'

export const GATEWAY_CATALOG: GatewayCatalogEntry[] = [
${entries.map(e => JSON.stringify(e)).join(',\n')},
]
`
writeFileSync(OUT, body)
const counts = entries.reduce((acc, e) => ((acc[e.type] = (acc[e.type] ?? 0) + 1), acc), {})
console.log(`Wrote ${entries.length} models to ${OUT}`, counts)
