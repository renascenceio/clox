#!/usr/bin/env node
/**
 * Regenerates src/lib/gateway/prices.generated.ts from the public
 * Vercel AI Gateway model list — the prices the gateway bills us.
 *
 *   node scripts/sync-gateway-prices.mjs
 *
 * Text models: USD per 1M tokens for input, output, cache reads and cache
 * writes. Image models with one flat price: USD per image.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/gateway/prices.generated.ts')

const res = await fetch('https://ai-gateway.vercel.sh/v1/models')
if (!res.ok) throw new Error(`Gateway model list ${res.status}`)
const { data } = await res.json()

const perM = v => (v == null || v === '' || Number.isNaN(Number(v)) ? undefined : Math.round(Number(v) * 1e6 * 10000) / 10000)

const text = {}
const image = {}
for (const m of data) {
  const p = m.pricing ?? {}
  if (m.type === 'language' && p.input != null && p.output != null) {
    const row = { in: perM(p.input), out: perM(p.output) }
    if (p.input_cache_read != null) row.cacheRead = perM(p.input_cache_read)
    if (p.input_cache_write != null) row.cacheWrite = perM(p.input_cache_write)
    text[m.id] = row
  }
  if ((m.type === 'image' || m.type === 'language') && p.image != null && !Number.isNaN(Number(p.image))) {
    image[m.id] = Number(p.image)
  }
}

const body = `// Generated by scripts/sync-gateway-prices.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
export type TextPrice = { in: number; out: number; cacheRead?: number; cacheWrite?: number }

/** USD per 1M tokens. */
export const TEXT_PRICES: Record<string, TextPrice> = ${JSON.stringify(text, null, 0).replace(/},"/g, '},\n  "').replace(/^{/, '{\n  ').replace(/}$/, '\n}')}

/** USD per image. */
export const IMAGE_PRICES: Record<string, number> = ${JSON.stringify(image, null, 2)}
`
writeFileSync(OUT, body)
console.log(`wrote ${Object.keys(text).length} text and ${Object.keys(image).length} image prices`)
